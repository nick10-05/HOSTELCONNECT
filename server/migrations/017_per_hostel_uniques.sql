-- Multi-tenant phase 2c: the rules that were for the whole database become each hostel's.
--
-- Migration 013 added a per-hostel unique index next to each global one, so the code of
-- the time kept its error names. Now that every query is scoped to its hostel (phase
-- 2b), the global ones would only stop two hostels from doing what each may do alone:
--   - users_email_lower_key: the same email may belong to a student of two hostels;
--     users_hostel_email_lower_key keeps it unique within each hostel.
--   - buildings_name_lower_key: two hostels may each have a "Block A";
--     buildings_hostel_name_lower_key keeps names unique within each hostel.
--   - return_polls_one_open: each hostel may have one open poll at a time;
--     return_polls_one_open_per_hostel keeps that rule.
-- Owners' Google accounts stay unique across all hostels (users_google_sub_key): one
-- Google account owns at most one hostel (decided in phase 0).
DROP INDEX users_email_lower_key;
DROP INDEX buildings_name_lower_key;
DROP INDEX return_polls_one_open;

-- Payment details: one row per hostel. The row's id was always 1 (one row for the whole
-- database), so a second hostel saving its details would have collided with the first
-- hostel's row. The id now comes from a sequence, and hostel_settings_hostel_key (one row
-- per hostel, migration 013) is what saving checks against (ON CONFLICT (hostel_id)).
ALTER TABLE hostel_settings DROP CONSTRAINT hostel_settings_id_check;
ALTER TABLE hostel_settings ALTER COLUMN id DROP DEFAULT;
ALTER TABLE hostel_settings ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 2);
